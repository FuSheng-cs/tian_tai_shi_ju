import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

// Approved home sources and lossless CG originals are retained for regeneration.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'art-source/pixel_city_20261104')
const relative = 'assets/images/pixel_city_20261104'
const output = path.join(root, 'public', relative)
await fs.mkdir(path.join(output, 'web'), { recursive: true })

const home = path.join(source, 'home-background.png')
for (const width of [960, 1672]) {
  await sharp(home).resize({ width, kernel: 'nearest' })
    .webp({ quality: 88, effort: 6 }).toFile(path.join(output, `home-${width}.webp`))
}
// The selected close-up gives the chat view the same face as the homepage.
await sharp(home).extract({ left: 930, top: 45, width: 460, height: 460 })
  .resize(240, 240, { kernel: 'nearest' })
  .webp({ lossless: true, effort: 6 }).toFile(path.join(output, 'avatar.webp'))
for (const size of [192, 512]) {
  await sharp(path.join(output, 'favicon.svg')).resize(size, size, { kernel: 'nearest' })
    .png().toFile(path.join(output, `app-icon-${size}.png`))
}

if (process.argv.includes('--home-only')) process.exit(0)

const frames = {
  'opening/opening_01': 'opening_01',
  'opening/opening_02': 'opening_02',
  'opening/opening_03': 'opening_03',
  'opening/opening_04': 'opening_04',
  // The last opening frame intentionally shares the first guarded scene.
  'opening/opening_05': 'state_guarded',
  'state/state_edge': 'state_edge',
  'state/state_guarded': 'state_guarded',
  'state/state_smoke': 'state_smoke',
  'state/state_turn_back': 'state_turn_back',
  'state/state_wavering': 'state_wavering',
  'emotion/emotion_curiosity': 'emotion_curiosity',
  'emotion/emotion_soft': 'emotion_soft',
  'emotion/emotion_sting': 'emotion_sting',
  'emotion/emotion_surprise': 'emotion_surprise',
  'ending/death_01': 'death_01',
  'ending/death_02': 'death_02',
  'ending/death_03': 'death_03',
  'ending/death_04': 'death_04',
  'ending/death_05': 'ending_death_05',
  'ending/end_acquaintance': 'end_acquaintance',
  'ending/end_disappear': 'end_disappear'
}

const assets = {}
for (const [name, stem] of Object.entries(frames)) {
  const input = path.join(source, `${stem}.png`)
  const original = path.join(output, 'originals', `${name}.webp`)
  await fs.mkdir(path.dirname(original), { recursive: true })
  try {
    await fs.access(input)
    await sharp(input).webp({ lossless: true, effort: 6 }).toFile(original)
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
    await fs.access(original)
  }
  const { width: sourceWidth } = await sharp(original).metadata()
  const item = {}
  for (const [key, width, quality] of [
    ['image', sourceWidth, 82], ['mobileImage', 900, 82], ['preview', 320, 60]
  ]) {
    const data = await sharp(original).resize({ width, withoutEnlargement: true, kernel: 'nearest' })
      .webp({ quality, effort: 6 }).toBuffer()
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 12)
    const filename = `${name.replace('/', '-')}-${key}-${hash}.webp`
    await fs.writeFile(path.join(output, 'web', filename), data)
    item[key] = `/${relative}/web/${filename}`
  }
  assets[name] = item
  console.log(name)
}

const code = `// Generated by scripts/build_pixel_city_assets.mjs.\nexport const CG_ASSETS = ${JSON.stringify(assets, null, 2).replaceAll('"', "'")} as const

export const CG_PREVIEW_BY_IMAGE: Record<string, string> = Object.fromEntries(
  Object.values(CG_ASSETS).flatMap(asset => [
    [asset.image, asset.preview], [asset.mobileImage, asset.preview]
  ])
)

export const getCGPreview = (url: string) => CG_PREVIEW_BY_IMAGE[url] || ''
`
await fs.writeFile(path.join(root, 'src/domain/cgAssets.generated.ts'), code)
